'use strict';

const font = require('./font');
const db = bytes => `    db ${bytes.join(', ')}`;
const lines = bytes => Array.from({ length: Math.ceil(bytes.length / 16) }, (_, i) => db(bytes.slice(i * 16, i * 16 + 16))).join('\n');

function generateROM({ rectangleEnabled, rectangleRuntime, choicesEnabled, choicesRuntime, choiceTables, dialogueEnabled, dialogueRuntime, poolEnabled, poolRuntime, poolData, poolError, header, headerBytes, mainCode, codeBanking, runtime, strings, graphics, symbols, zeroError, indexError, arrayLiterals, sound, soundRuntime, save, saveRuntime, animation, animationRuntime, music, musicRuntime }) {
  const gray = [0x7fff, 0x56b5, 0x294a, 0];
  const bg = Array.from({ length: 8 }, () => [...gray]);
  const obj = Array.from({ length: 8 }, () => [...gray]);
  for (const asset of graphics.assets.filter(asset => !['collision', 'manual'].includes(asset.kind) && asset.palette)) (asset.kind === 'sprite' ? obj : bg)[asset.paletteIndex] = asset.palette;
  const paletteBytes = [...bg.flat(), ...obj.flat()].flatMap(color => [color & 255, color >> 8]);
  const mutableMaps = graphics.assets.filter(asset => asset.mutable);
  const assetData = graphics.assets.filter(asset => !['world', 'clip'].includes(asset.kind)).map(asset => `SECTION "${asset.label} data", ROMX[$${asset.address.toString(16)}], BANK[${asset.bank}]\n` + (asset.kind === 'manual'
    ? asset.mutable ? `${asset.label}:\n${lines(asset.initialCells)}` : `${asset.label}:\n    dw ${asset.label}Definitions\n${lines(asset.cellMap)}\n${asset.label}Definitions:\n${lines(asset.definitions.flat())}`
    : `${asset.label}:\n${lines(asset.maps.flat())}`)).join('\n');
  const descriptors = graphics.assets.map(asset => `${db([asset.mutable ? 7 : asset.kind === 'clip' ? 8 : asset.kind === 'sprite' ? 1 : asset.kind === 'collision' ? 3 : asset.kind === 'manual' ? 4 : asset.kind === 'tile' ? 5 : asset.kind === 'world' ? 6 : 2, asset.columns, asset.rows, asset.frames, asset.paletteIndex, asset.kind === 'sprite' ? asset.columns * asset.rows : 0])}\n    dw ${asset.mutable ? asset.label + 'RAM' : asset.label}, BANK(${asset.label})`).join('\n');
  const capacity = graphics.banking.romKB ? `\nSECTION "Requested ROM capacity", ROMX[$7FFF], BANK[${graphics.banking.romKB / 16 - 1}]\n    db $FF\n` : '';
  return `; Generated by Pyson. Signed 16-bit integer and buffered graphics runtime.
DEF CODE_BANKING_ENABLED EQU ${codeBanking.objects.length ? 1 : 0}
DEF FRAME_CLOCK_ENABLED EQU ${graphics.frameClock ? 1 : 0}
DEF CARTRIDGE_CONTROLLER EQU ${{rom_only: 0, mbc1: 1, mbc3: 3, mbc5: 5}[header.controller]}
DEF MUSIC_ENABLED EQU ${music.enabled ? 1 : 0}
DEF WAVE_MUSIC_ENABLED EQU ${music.waveEnabled ? 1 : 0}
DEF SOUND_ENABLED EQU ${sound.enabled ? 1 : 0}
DEF SAVE_ENABLED EQU ${save.enabled ? 1 : 0}
DEF SAVE_CAPACITY EQU ${save.capacity}
DEF SAVE_RAM_BANKS EQU ${save.ramBanks}
DEF ANIMATION_ENABLED EQU ${animation.enabled ? 1 : 0}
DEF STREAM_ENABLED EQU ${graphics.streaming ? 1 : 0}
DEF CLIP_ENABLED EQU ${graphics.clips?.enabled ? 1 : 0}
DEF TILE_GRID_ENABLED EQU ${graphics.tileGrid ? 1 : 0}
DEF TILE_FIELD_ENABLED EQU ${graphics.tileField ? 1 : 0}
DEF CLIP_TILE_BASE EQU ${graphics.clips?.base || 0}
DEF CLIP_TILE_SPAN EQU ${graphics.clips?.span || 0}
DEF STREAM_TILE_BASE EQU ${graphics.tileData.length / 16}
DEF WINDOW_ENABLED EQU ${graphics.window ? 1 : 0}
DEF CHOICES_ENABLED EQU ${choicesEnabled ? 1 : 0}
DEF RANDOM_ENABLED EQU ${graphics.random ? 1 : 0}
DEF MUTABLE_ENABLED EQU ${mutableMaps.length || graphics.mutation ? 1 : 0}
DEF FORMAT_ENABLED EQU ${graphics.format ? 1 : 0}
DEF PORTRAIT_ENABLED EQU ${graphics.portraits ? 1 : 0}
DEF WINDOW_BUFFER_BYTES EQU 20 * 18
DEF BG_BUFFER_ROWS EQU ${graphics.scrolling ? 32 : 18}
DEF BG_BUFFER_BYTES EQU BG_BUFFER_ROWS * 32
DEF COLOR_ENABLED EQU ${header.target === 'dmg' ? 0 : 1}
DEF ASSET_COUNT EQU ${graphics.assets.length}
${dialogueEnabled ? Object.entries({ SPACE: ' ', HORIZONTAL: '-', VERTICAL: '|', CORNER: '+', MORE: '>' }).map(([name, glyph]) => `DEF DIALOGUE_${name}_TILE EQU ${font.ids.get(glyph)}`).join('\n') : ''}
DEF MINUS_TILE EQU ${font.ids.get('-')}
${graphics.frameClock ? 'SECTION "Frame clock vector", ROM0[$0040]\n    jp FrameClockInterrupt' : ''}
SECTION "Header", ROM0[$0100]
    nop
    jp Start
    ds 48, 0
${db(headerBytes)}
SECTION "Program", ROM0[$0150]
Start:
    di
    ld sp, $E000
${header.cpu_speed === 'double' ? `    push af
    call InitCPUSpeed
    pop af` : ''}
    call InitDisplay
    call InitState
${graphics.frameClock ? '    call InitFrameClock' : ''}
MainStart:
${mainCode.join('\n')}
MainFinish:
    call RefreshScreen
ProgramIdle:
IF SOUND_ENABLED
    call WaitVBlank
ENDC
    jp ProgramIdle
${codeBanking.runtimeWrappers}
${header.cpu_speed === 'double' ? `; The boot accumulator identifies CGB hardware. Preserve it for InitDisplay.
InitCPUSpeed:
    cp $11
    ret nz
    ldh a, [$FF4D]
    bit 7, a
    ret nz
    xor a
    ldh [$FFFF], a
    ld a, $30
    ldh [$FF00], a
    ld a, 1
    ldh [$FF4D], a
    stop
    ret` : ''}
${runtime}
${soundRuntime}
${musicRuntime}
${saveRuntime}
${animationRuntime}
${poolRuntime}
${dialogueRuntime}
${choicesRuntime}
${rectangleRuntime}
${mutableMaps.length || graphics.mutation ? `InitMutableMaps:
${mutableMaps.map(asset => `    ld a, ${asset.id}\n    ld [wArg0], a\n    xor a\n    ld [wArg0 + 1], a\n    call ResetMutableMap`).join('\n')}
    ret
ResetMutableMap:
    ld a, [wArg0 + 1]
    and a
    jr nz, .invalid
    ld a, [wArg0]
${mutableMaps.map(asset => `    cp ${asset.id}\n    jp z, .map${asset.id}`).join('\n')}
.invalid:
    ld hl, 0
    ret
${mutableMaps.map(asset => `.map${asset.id}:\n    ld bc, BANK(${asset.label})\n    call SelectROMBank\n    ld hl, ${asset.label}\n    ld de, ${asset.label}RAM\n    ld bc, ${asset.initialCells.length}\n    call CopyArray\n    ld hl, 1\n    ret`).join('\n')}
MutableTileDefinitions:
${lines(graphics.assets.flatMap(asset => asset.kind === 'tile' ? [asset.maps[0][0], asset.paletteIndex | (asset.solid ? 128 : 0), asset.terrain] : [0, 0, 0]))}
SetMapTile:
    call QueryMapOffset
    jr c, .invalid
    ld a, [wAssetCount]
    cp 7
    jr nz, .invalid
    call ManualCellAddress
    push hl
    ld a, [wArg3 + 1]
    and a
    jr nz, .badTile
    ld a, [wArg3]
    call FindAsset
    jr c, .badTile
    ld a, [hl]
    cp 5
    jr nz, .badTile
    ld a, [wArg3]
    ld l, a
    ld h, 0
    ld d, h
    ld e, l
    add hl, hl
    add hl, de
    ld de, MutableTileDefinitions
    add hl, de
    pop de
    ld bc, 3
    call CopyArray
    ld hl, 1
    ret
.badTile:
    pop hl
.invalid:
    ld hl, 0
    ret
` : ''}
${poolEnabled ? `PoolHandleError:\n    ld hl, ${poolError}\n    jp RuntimeError` : ''}
DivisionByZero:
    ld hl, ${zeroError}
    jp RuntimeError
ArrayIndexError:
    ld hl, ${indexError}
RuntimeError:
${graphics.sourceDiagnostics ? '    push hl' : ''}
IF SOUND_ENABLED
    call StopSound
IF MUSIC_ENABLED
    call StopMusic
ENDC
ENDC
IF WINDOW_ENABLED
    call HideWindow
ENDC
    call ResetCamera
    xor a
    ld [wTextPalette], a
${graphics.sourceDiagnostics ? `    ld a, [wErrorContext]
    ld l, a
    ld a, [wErrorContext + 1]
    ld h, a
    or l
    jr z, .noContext
    ld b, 0
    ld c, 14
    call PrintAt
.noContext:
    pop hl` : ''}
    ld b, 0
    ld c, 16
    call PrintAt
    call RefreshScreen
.error:
    jp .error
${[...strings.values()].map(value => `${value.label}:\n${lines(value.tiles)}`).join('\n')}
${arrayLiterals.map(value => `${value.label}:\n${lines(value.bytes)}`).join('\n')}
${choiceTables.map(table => `${table.label}:\n    db ${table.labels.length}\n    dw ${table.labels.join(', ')}`).join('\n')}
${(graphics.textFormats || []).map(table => `${table.label}:\n${lines(table.bytes)}`).join('\n')}
${poolData}
${[...sound.used.values()].map(effect => `${effect.label}:\n${lines(effect.bytes)}`).join('\n')}
${[...music.used.values()].map(track => `${track.label}:\n${lines(track.bytes)}`).join('\n')}
${[...animation.used.values()].map(definition => `${definition.label}:\n${lines(definition.bytes)}`).join('\n')}
DigitTiles:
${db(Array.from({ length: 10 }, (_, i) => font.ids.get(String(i))))}
DefaultPalettes:
${lines(paletteBytes)}
AssetDescriptors:
${descriptors}
${graphics.tileGrid ? `GridTileDefinitions:\n${lines(graphics.assets.flatMap(asset => asset.kind === 'tile' ? [1, asset.maps[0][0], asset.paletteIndex] : [0,0,0]))}` : ''}
${graphics.paletteLiterals.map(palette => `${palette.label}:\n${db(palette.bytes)}`).join('\n')}
${codeBanking.objects.map(fn => `SECTION "Function ${fn.label}", ROMX[$${fn.address.toString(16)}], BANK[${fn.bank}]\n${fn.code.join('\n')}\nASSERT @ - ${fn.label} == ${fn.bytes}\n`).join('\n')}
SECTION "Tile graphics", ROMX[$4000], BANK[1]
Font:
${lines(graphics.tileData)}
FontEnd:
${assetData}
${(graphics.tables || []).map(table => `SECTION "${table.label} data", ROMX[$${table.address.toString(16)}], BANK[${table.bank}]\n${table.label}:\n${lines(table.data.length ? table.data : [0])}\nASSERT @ - ${table.label} == ${table.bytes}`).join('\n')}
${(graphics.worldObjects || []).map(object => `SECTION "${object.label} data", ROMX[$${object.address.toString(16)}], BANK[${object.bank}]\n${object.body}`).join('\n')}

SECTION "OAM shadow", WRAM0[$C000]
wShadowOAM: ds 160
SECTION "Runtime state", WRAM0
wIsCGB: ds 1
wStateStart:
${graphics.tileField ? 'wFieldLength0: ds 2\nwFieldLength1: ds 2\nwFieldLength2: ds 2\nwFieldBank0: ds 2\nwFieldBank1: ds 2\nwFieldBank2: ds 2\nwFieldPalette: ds 128\nwFieldMask: ds 1\nwFieldWidth: ds 1\nwFieldHeight: ds 1\nwFieldX: ds 1\nwFieldY: ds 1\nwFieldRow: ds 1\nwFieldLeft: ds 1\nwFieldColumns: ds 2\nwFieldRows: ds 2' : ''}
${graphics.tileGrid ? 'wGridLength: ds 2\nwGridBank: ds 2\nwGridPointer: ds 2\nwGridCols: ds 1\nwGridX: ds 1\nwGridY: ds 1\nwGridCol: ds 1\nwGridRow: ds 1' : ''}
${graphics.clips?.enabled ? 'wClipFront: ds 1\nwClipTarget: ds 1\nwClipPending: ds 1\nwClipTileBase: ds 1\nwClipFrame: ds 1\nwClipX: ds 1\nwClipY: ds 1\nwClipLastX: ds 1\nwClipLastY: ds 1\nwClipLastCols: ds 1\nwClipLastRows: ds 1' : ''}
${graphics.frameClock ? 'wFrameCount: ds 2\nwFrameAudioCursor: ds 2' : ''}
wButtonsHeld: ds 1
wButtonsPressed: ds 1
wPrintX: ds 1
wTextPalette: ds 1
wCellTile: ds 1
wFrontMap: ds 1
wFlushRow: ds 1
wFlushMask: ds 1
wFlushBase: ds 1
wMapPending: ds 1
wPaletteDirty: ds 1
wOAMDirty: ds 1
wDirtyRows: ds BG_BUFFER_ROWS
wBGPalettes: ds 64
wOBJPalettes: ds 64
wSpriteCounts: ds 40
wBGTiles: ds BG_BUFFER_BYTES
wBGAttrs: ds BG_BUFFER_BYTES
DEF ATTR_OFFSET EQU wBGAttrs - wBGTiles
${Array.from({ length: 7 }, (_, i) => `wArg${i}: ds 2`).join('\n')}
wDescriptor: ds 2
wAssetCols: ds 1
wAssetRows: ds 1
wAssetPalette: ds 1
wAssetCount: ds 1
wAssetMap: ds 2
wSpriteSlot: ds 1
wSpriteRow: ds 1
wSpriteCol: ds 1
wSpriteFlags: ds 1
wSpriteY: ds 1
wSpriteX: ds 1
wSpriteTile: ds 1
wWorldDrawing: ds 1
wWorldActive: ds 1
wWorldMap: ds 2
wWorldCols: ds 1
wWorldRows: ds 1
wCameraX: ds ${graphics.streaming ? 2 : 1}
wCameraY: ds ${graphics.streaming ? 2 : 1}
wCameraDirty: ds 1
${graphics.streaming ? `wAssetBank: ds 2
wStreamActive: ds 1
wStreamLCDPaused: ds 1
wStreamPhase: ds 1
wStreamTargetX: ds 1
wStreamTargetY: ds 1
wStreamWantedX: ds 2
wStreamWantedY: ds 2
wStreamJump: ds 1
wStreamMoveX: ds 1
wStreamMoveY: ds 1
wStreamWorldRegionColumns: ds 1
wStreamWorldRegionRows: ds 1
wStreamScan: ds 2
wStreamMapReady: ds 1
wStreamOverlapLeft: ds 1
wStreamOverlapRight: ds 1
wStreamOverlapTop: ds 1
wStreamOverlapBottom: ds 1
wStreamUploadBudget: ds 1
wStreamRecordBudget: ds 1
wStreamScanBudget: ds 1
wStreamSlot: ds 1
wStreamTileID: ds 2
wStreamCachePointer: ds 2
wStreamCellTile: ds 1
wStreamCellPalette: ds 1
wStreamCache: ds (256 - STREAM_TILE_BASE) * 2
wStreamHeaderBank: ds 2
wStreamChunkColumns: ds 1
wStreamRegionColumns: ds 1
wStreamChunkTable: ds 2
wStreamRegionTable: ds 2
wStreamChunkIndex: ds 1
wStreamChunkBank: ds 2
wStreamChunkMap: ds 2
wStreamChunkDefinitions: ds 2
wStreamRegionX: ds 1
wStreamRegionY: ds 1
wStreamNextX: ds 1
wStreamNextY: ds 1
wStreamOriginX: ds 1
wStreamOriginY: ds 1
wStreamCopyRow: ds 1
wStreamCopyBase: ds 2
wStreamCopyNext: ds 2
wStreamTileNext: ds 2
wStreamTileCount: ds 1
wStreamPalette: ds 1
wStreamTilePointer: ds 2
wStreamTileBank: ds 2
wStreamMapPointer: ds 2
wStreamMapBank: ds 2` : ''}
wMapRow: ds 1
wMapCol: ds 1
IF WINDOW_ENABLED
wWindowOn: ds 1
wWindowX: ds 1
wWindowY: ds 1
wWindowText: ds 1
wWindowControlDirty: ds 1
wWindowCellChanged: ds 1
wWindowRow: ds 1
wWindowDirtyCount: ds 1
wWindowLCDPaused: ds 1
wWindowDirtyRows: ds 18
wWindowTiles: ds WINDOW_BUFFER_BYTES
wWindowAttrs: ds WINDOW_BUFFER_BYTES
DEF WINDOW_ATTR_OFFSET EQU wWindowAttrs - wWindowTiles
ENDC
${sound.enabled ? `wSoundActive: ds 1
wSoundPointer: ds 2
wSoundSteps: ds 1
wSoundFrames: ds 1
wSoundKind: ds 1
wSoundDuty: ds 1
wSoundPriority: ds 1
wSoundMuted: ds 1
wSoundLeft: ds 1
wSoundRight: ds 1` : ''}
wNumberNegative: ds 1
${codeBanking.objects.length ? 'wExecutionBank: ds 2' : ''}
${music.enabled ? 'wMusicDefinition: ds 2\nwMusicPointer: ds 2\nwMusicSteps: ds 1\nwMusicFrames: ds 1\nwMusicActive: ds 1\nwMusicPaused: ds 1' : ''}
${music.waveEnabled ? 'wWaveMusicDefinition: ds 2\nwWaveMusicPointer: ds 2\nwWaveMusicSteps: ds 1\nwWaveMusicFrames: ds 1\nwWaveMusicActive: ds 1\nwWaveMusicPaused: ds 1' : ''}
${animation.enabled ? 'wAnimationStates: ds 40 * 6' : ''}
wNumberPointer: ds 2
wNumberBuffer: ds 7
wDivisor: ds 2
wDivisorNegative: ds 1
wQuotientNegative: ds 1
wRemainder: ds 2
${graphics.fixed ? 'wFixedLeft: ds 4\nwFixedRight: ds 2\nwFixedSign: ds 1\nwFixedCount: ds 1' : ''}
${poolEnabled ? 'wPoolResult: ds 2\nwPoolSlot: ds 2\nwPoolRemaining: ds 2\nwPoolStride: ds 2\nwPoolDefaults: ds 2\nwPoolFieldBytes: ds 2\nwPoolActiveCount: ds 1' : ''}
${dialogueEnabled ? 'wDialoguePointer: ds 2\nwDialogueActive: ds 1\nwDialogueWaiting: ds 1\nwDialogueFinished: ds 1\nwDialogueJustStarted: ds 1\nwDialogueSpeed: ds 1\nwDialogueCounter: ds 1\nwDialogueX: ds 1\nwDialogueY: ds 1\nwDialogueWordStart: ds 1\nwDialoguePalette: ds 1\nwDialogueFast: ds 1' : ''}
${choicesEnabled ? 'wChoicesMode: ds 1\nwChoicesTable: ds 2\nwChoicesCount: ds 1\nwChoicesSelected: ds 1\nwChoicesResult: ds 1\nwChoicesCancelled: ds 1\nwChoicesCancelAllowed: ds 1\nwChoicesSelectedPalette: ds 1\nwChoicesRow: ds 1' : ''}
${rectangleEnabled ? 'wRectArgs: ds 16' : ''}
${graphics.terrainRectangles ? 'wTerrainRectLeft: ds 1\nwTerrainRectRight: ds 1\nwTerrainRectTop: ds 1\nwTerrainRectBottom: ds 1\nwTerrainRectColumn: ds 1\nwTerrainRectRow: ds 1' : ''}
${graphics.random ? 'wRandomState: ds 2\nwRandomMinimum: ds 2\nwRandomSpan: ds 2\nwRandomThreshold: ds 2' : ''}
${graphics.sourceDiagnostics ? 'wErrorContext: ds 2' : ''}
${graphics.format ? 'wFormatBuffer: ds 256\nwFormatRemaining: ds 1' : ''}
${graphics.format && dialogueEnabled ? 'wDialogueSnapshot: ds 256' : ''}
${graphics.portraits ? 'wDialogueLeft: ds 1\nwPortraitEnabled: ds 1\nwPortraitPalette: ds 1\nwPortraitTiles: ds 4' : ''}
${mutableMaps.map(asset => `${asset.label}RAM: ds ${asset.initialCells.length}`).join('\n')}
${symbols.filter(symbol => !symbol.readOnly).map(symbol => `${symbol.label}: ds ${symbol.bytes ?? 2}`).join('\n')}
wStateEnd:
SECTION "Stack", WRAMX[$D000], BANK[1]
    ds $1000
SECTION "DMA routine", HRAM[$FF80]
hOAMDMA: ds DMARoutineEnd - DMARoutine
${capacity}`;
}

module.exports = { generateROM };
